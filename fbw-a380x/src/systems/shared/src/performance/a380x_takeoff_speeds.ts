const temperatureBands: ReadonlyArray<readonly [number, readonly number[]]> = [
  [0, [35, 43, 50]],
  [1_000, [30, 38, 47, 48]],
  [2_000, [26, 34, 43, 46]],
  [3_000, [24, 29, 39, 44]],
  [4_000, [25, 34, 42]],
  [5_000, [20, 30, 40]],
  [6_000, [18, 25, 36]],
  [7_000, [21, 32]],
  [8_000, [18, 27]],
  [9_000, [12, 22]],
  [10_000, [17]],
];

export function getA380TakeoffTableSpeeds(
  tow: number,
  conf: number,
  pressureAlt: number,
  oat: number,
): readonly [number, number, number] {
  const weightIndex = Math.max(0, Math.min(12, Math.floor((tow - 300_000) / 20_000)));
  const altitudeIndex = Math.max(0, Math.min(10, Math.round(pressureAlt / 1_000)));
  const thresholds = temperatureBands[altitudeIndex][1];
  const temperatureIndex = Math.min(
    thresholds.findIndex((upper) => oat <= upper),
    3,
  );
  const column = temperatureIndex < 0 ? Math.min(thresholds.length - 1, 3) : temperatureIndex;
  return speedTable[conf - 1][weightIndex][column];
}
